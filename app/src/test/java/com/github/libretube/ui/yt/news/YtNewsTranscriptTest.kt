package com.github.libretube.ui.yt.news

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class YtNewsTranscriptTest {
    @Test
    fun ttmlCuesWithBreaksAndEntities() {
        val ttml = """
            <?xml version="1.0" encoding="utf-8" ?><tt xml:lang="de" xmlns="http://www.w3.org/ns/ttml">
            <head></head><body><div>
            <p begin="00:00:01.200" end="00:00:03.000" style="s2">Guten Abend,<br />meine Damen &amp; Herren.</p>
            <p begin="00:01:05.500" end="00:01:08.000">[Musik]</p>
            <p begin="00:01:09.000" end="00:01:10.000">Das Wetter: &#39;sonnig&#39;</p>
            </div></body></tt>
        """.trimIndent()
        val cues = YtNewsCaptions.parse(ttml)
        assertEquals(2, cues.size)
        assertEquals(1.2, cues[0].startSec, 1e-9)
        assertEquals("Guten Abend, meine Damen & Herren.", cues[0].text)
        assertEquals(69.0, cues[1].startSec, 1e-9)
        assertEquals("Das Wetter: 'sonnig'", cues[1].text)
    }

    @Test
    fun rollingAutoCaptionsAreKeptOnce() {
        val vtt = """
            WEBVTT
            Kind: captions
            Language: de

            00:00:00.000 --> 00:00:02.500 align:start position:0%
            die<00:00:00.500><c> Regierung</c><00:00:01.000><c> hat</c>

            00:00:02.500 --> 00:00:02.510 align:start position:0%
            die Regierung hat

            00:00:02.510 --> 00:00:05.000 align:start position:0%
            die Regierung hat
            heute<00:00:03.000><c> entschieden</c>

            00:00:05.000 --> 00:00:05.010
            heute entschieden
        """.trimIndent()
        val cues = YtNewsCaptions.parse(vtt)
        assertEquals(listOf("die Regierung hat", "heute entschieden"), cues.map { it.text })
        assertEquals(0.0, cues[0].startSec, 1e-9)
        assertEquals(2.51, cues[1].startSec, 1e-9)
    }

    @Test
    fun srtIsRead() {
        val srt = "1\r\n00:00:01,500 --> 00:00:03,000\r\n- Hallo\r\n\r\n2\r\n01:00:00,000 --> 01:00:02,000\r\nZweite Zeile\r\n"
        val cues = YtNewsCaptions.parse(srt)
        assertEquals(listOf("Hallo", "Zweite Zeile"), cues.map { it.text })
        assertEquals(3600.0, cues[1].startSec, 1e-9)
    }

    @Test
    fun unknownTextGivesNoCues() {
        assertTrue(YtNewsCaptions.parse("").isEmpty())
        assertTrue(YtNewsCaptions.parse("{\"events\": []}").isEmpty())
    }

    @Test
    fun timeFormats() {
        assertEquals(3723.5, YtNewsCaptions.time("01:02:03.500")!!, 1e-9)
        assertEquals(63.25, YtNewsCaptions.time("01:03,250")!!, 1e-9)
        assertEquals(3.5, YtNewsCaptions.time("3.5s")!!, 1e-9)
        assertEquals(1.5, YtNewsCaptions.time("1500ms")!!, 1e-9)
        assertEquals(2.0, YtNewsCaptions.time("20000000t")!!, 1e-9)
        assertEquals(3723.0, YtNewsCaptions.time("01:02:03:12")!!, 1e-9)
        assertNull(YtNewsCaptions.time("abc"))
    }

    @Test
    fun pickPrefersManualInTheSpokenLanguage() {
        val tracks = listOf(
            YtNewsTrack("en", autoGenerated = false),
            YtNewsTrack("de", autoGenerated = true),
            YtNewsTrack("de-DE", autoGenerated = false),
        )
        assertEquals(2, YtNewsCaptions.pick(tracks))
    }

    @Test
    fun pickFallsBackToRecognisedThenPreferred() {
        assertEquals(1, YtNewsCaptions.pick(listOf(YtNewsTrack("en", false), YtNewsTrack("fr", true))))
        assertEquals(1, YtNewsCaptions.pick(listOf(YtNewsTrack("fr", false), YtNewsTrack("de", false))))
        assertEquals(0, YtNewsCaptions.pick(listOf(YtNewsTrack("fr", false), YtNewsTrack("it", false))))
        assertNull(YtNewsCaptions.pick(emptyList()))
    }

    @Test
    fun passagesCloseAtSentencesAndPauses() {
        val cues = listOf(
            YtNewsCue(0.0, "Die Bundesregierung hat heute nach langen Verhandlungen"),
            YtNewsCue(3.0, "ein neues Klimapaket beschlossen, das ab Januar gilt."),
            YtNewsCue(6.0, "Kritik kommt"),
            YtNewsCue(40.0, "Zum Wetter."),
        )
        val passages = YtNewsTranscriptDoc.passages(cues)
        assertEquals(3, passages.size)
        assertEquals(0L, passages[0].first)
        assertTrue(passages[0].second.endsWith("ab Januar gilt."))
        assertEquals(6L to "Kritik kommt", passages[1])
        assertEquals(40L to "Zum Wetter.", passages[2])
    }

    @Test
    fun documentMapsCharactersToSeconds() {
        val cues = listOf(YtNewsCue(5.0, "Erste Meldung."), YtNewsCue(65.0, "Zweite Meldung."), YtNewsCue(3725.0, "Spät."))
        val doc = YtNewsTranscriptDoc.build(cues)
        assertEquals("[0:05] Erste Meldung.\n[1:05] Zweite Meldung.\n[1:02:05] Spät.\n", doc.text)
        assertEquals(3, doc.lines)
        assertEquals(5L, doc.secondAt(0))
        assertEquals(5L, doc.secondAt(20))
        val second = doc.text.indexOf("[1:05]")
        assertEquals(65L, doc.secondAt(second))
        assertEquals(65L, doc.secondAt(second + 8))
        assertEquals(3725L, doc.secondAt(doc.text.length - 1))
        assertFalse(doc.cut)
    }

    @Test
    fun offsetsCountCodePoints() {
        // an emoji is two chars in Kotlin but one character for the API
        val doc = YtNewsTranscriptDoc.build(listOf(YtNewsCue(1.0, "Achtung 😀 hier."), YtNewsCue(30.0, "Danach.")))
        val utf16 = doc.text.indexOf("[0:30]")
        val codePoint = doc.text.codePointCount(0, utf16)
        assertEquals(utf16 - 1, codePoint)
        assertEquals(30L, doc.secondAt(codePoint))
        assertEquals(30L, doc.resolve(codePoint, "[0:30] Danach."))
    }

    @Test
    fun resolveFindsTheQuoteWhenTheIndexIsOff() {
        val doc = YtNewsTranscriptDoc.build(listOf(YtNewsCue(2.0, "Eins."), YtNewsCue(50.0, "Der Haushalt steht.")))
        assertEquals(50L, doc.resolve(0, "Der Haushalt steht."))
        assertEquals(2L, doc.resolve(0, "[0:02] Eins."))
        assertEquals(50L, doc.resolve(doc.text.indexOf("Der"), null))
        assertNull(doc.resolve(10_000, "nicht im Text"))
    }

    @Test
    fun longTranscriptsAreCutAtALine() {
        val cues = (0 until 50).map { YtNewsCue(it * 30.0, "Satz Nummer $it ist hier.") }
        val doc = YtNewsTranscriptDoc.build(cues, maxChars = 200)
        assertTrue(doc.cut)
        assertTrue(doc.text.length <= 200)
        assertTrue(doc.text.endsWith("\n"))
    }

    @Test
    fun stamps() {
        assertEquals("0:00", YtNewsTranscriptDoc.stamp(0))
        assertEquals("9:59", YtNewsTranscriptDoc.stamp(599))
        assertEquals("1:00:00", YtNewsTranscriptDoc.stamp(3600))
    }
}
