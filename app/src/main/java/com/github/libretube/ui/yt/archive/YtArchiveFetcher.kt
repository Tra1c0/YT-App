package com.github.libretube.ui.yt.archive

import android.util.Log
import com.github.libretube.api.MediaServiceRepository
import com.github.libretube.api.obj.PipedStream
import com.github.libretube.api.obj.Streams
import com.github.libretube.db.obj.DownloadItem
import com.github.libretube.enums.FileType
import com.github.libretube.repo.DownloadProgressResult
import com.github.libretube.repo.DownloadProvider
import com.github.libretube.repo.RawByteStreamDownloadProvider
import com.github.libretube.repo.SabrDownloadProvider
import com.github.libretube.ui.yt.news.YtNewsCaptions
import com.github.libretube.ui.yt.news.YtNewsTrack
import com.github.libretube.util.YtStreamError
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.delay
import kotlinx.coroutines.runInterruptible
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.Json
import okhttp3.HttpUrl.Companion.toHttpUrl
import okhttp3.OkHttpClient
import okhttp3.Request
import okio.buffer
import okio.sink
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.exceptions.ReCaptchaException
import java.io.File
import java.io.IOException
import java.nio.file.StandardOpenOption
import java.util.concurrent.TimeUnit

/**
 * YT: fetches what an archive tier keeps, through the app's own paths: the stream info of
 * NewPipe ([MediaServiceRepository.getStreams]), captions through NewPipe's downloader (as the news
 * summaries do, [YtNewsCaptions.pick]: a manual track in the spoken language, else the
 * recognised one), stream bytes with LibreTube's download providers (ranged HTTP, or SABR where
 * YouTube only offers that), and small images (thumbnail, storyboard sheets) with a plain client.
 *
 * Errors come out typed: [Blocked] (bot check, 429: the run stops and the archive pauses),
 * [Gone] (the video is private or deleted) and anything else as a normal failure.
 */
class YtArchiveFetcher(private val store: YtArchiveStore) {
    class Blocked(reason: String) : IOException(reason)
    class Gone(val kind: YtStreamError.Kind) : IOException(kind.name)

    private val json = Json { encodeDefaults = true }

    private val client: OkHttpClient by lazy {
        OkHttpClient.Builder()
            .connectTimeout(15, TimeUnit.SECONDS)
            .readTimeout(30, TimeUnit.SECONDS)
            .build()
    }

    /** The stream info of [videoId]; one NewPipe request (it may make a few HTTP calls). */
    suspend fun streams(videoId: String): Streams = try {
        MediaServiceRepository.instance.getStreams(videoId)
    } catch (e: CancellationException) {
        throw e
    } catch (e: Exception) {
        throw typed(e)
    }

    /** A thrown error as the archive treats it. */
    fun typed(e: Throwable): Throwable {
        if (e is Blocked || e is Gone) return e
        val kind = YtStreamError.classify(e)
        return when {
            kind == YtStreamError.Kind.BOT_CHECK -> Blocked(e.message ?: "bot check")
            YtStreamError.removesFromFeed(kind) -> Gone(kind)
            else -> e
        }
    }

    /**
     * Tier 1: chapters and description from [streams] into the meta, the small thumbnail and the
     * transcript. Returns the meta with the text part measured.
     */
    suspend fun saveText(meta: YtArchiveMeta, streams: Streams?, now: Long): YtArchiveMeta = withContext(Dispatchers.IO) {
        val files = store.files(meta.videoId) ?: return@withContext meta
        files.dir.mkdirs()
        var next = meta
        if (streams != null) {
            next = next.copy(
                title = streams.title.ifBlank { meta.title },
                description = streams.description.ifBlank { meta.description.orEmpty() }.take(MAX_DESCRIPTION),
                channelName = streams.uploader.ifBlank { meta.channelName.orEmpty() },
                durationSec = streams.duration.takeIf { it > 0 } ?: meta.durationSec,
                chapters = streams.chapters.map { YtArchiveChapter(it.start, it.title) },
            )
        }
        if (!files.thumbnail.isFile) {
            runCatching { fetchFile(thumbnailUrl(meta.videoId), files.thumbnail, MAX_IMAGE_BYTES) }
                .onFailure { if (it is Blocked) throw it else Log.i(TAG, "thumbnail failed: $it") }
        }
        if (streams != null && !files.transcript.isFile) {
            val picked = transcript(streams)
            if (picked != null) {
                YtArchiveText.write(picked.first, files.transcript)
                next = next.copy(transcriptLanguage = picked.second.code, transcriptAuto = picked.second.autoGenerated)
            }
        }
        store.put(next)
        measured(next)
    }

    /** The caption lines of the best track, and that track; null without captions. */
    private suspend fun transcript(streams: Streams): Pair<List<YtArchiveText.Line>, YtNewsTrack>? {
        val tracks = streams.subtitles.filter { !it.url.isNullOrBlank() }
        val described = tracks.map { YtNewsTrack(it.code, it.autoGenerated == true) }
        val pick = YtNewsCaptions.pick(described) ?: return null
        val url = tracks[pick].url ?: return null
        val body = try {
            runInterruptible(Dispatchers.IO) { NewPipe.getDownloader().get(url).responseBody() }
        } catch (e: ReCaptchaException) {
            throw Blocked("429 captions")
        } catch (e: IOException) {
            Log.i(TAG, "captions failed: $e")
            return null
        }
        val lines = YtArchiveText.lines(YtNewsCaptions.parse(body))
        return if (lines.isEmpty()) null else lines to described[pick]
    }

    /** Tier 2: the smallest audio stream and the storyboard stills. */
    suspend fun saveAudio(meta: YtArchiveMeta, streams: Streams, now: Long): YtArchiveMeta = withContext(Dispatchers.IO) {
        val files = store.files(meta.videoId) ?: return@withContext meta
        val sabr = sabr(streams)
        val index = YtArchiveRules.pickAudio(streams.audioStreams.map(::choice), sabr)
            ?: throw IOException("no audio stream")
        val stream = streams.audioStreams[index]
        files.dir.mkdirs()
        downloadStream(meta.videoId, streams, stream, FileType.AUDIO, files.audio)
        runCatching { saveBoard(streams, files) }
            .onFailure { if (it is Blocked) throw it else Log.i(TAG, "storyboard failed: $it") }
        val next = meta.copy(tierLevel = maxOf(meta.tierLevel, YtArchiveTier.AUDIO.level), tierAt = now, audioMime = stream.mimeType)
        store.put(next)
        measured(next)
    }

    /** Tier 3: the 144p video stream (played together with the audio file). */
    suspend fun saveVideo(meta: YtArchiveMeta, streams: Streams, now: Long): YtArchiveMeta = withContext(Dispatchers.IO) {
        val files = store.files(meta.videoId) ?: return@withContext meta
        val index = YtArchiveRules.pickVideo(streams.videoStreams.map(::choice), sabr(streams))
            ?: throw IOException("no video stream")
        val stream = streams.videoStreams[index]
        downloadStream(meta.videoId, streams, stream, FileType.VIDEO, files.video)
        val next = meta.copy(tierLevel = YtArchiveTier.VIDEO.level, tierAt = now, videoMime = stream.mimeType, videoHeight = stream.height)
        store.put(next)
        measured(next)
    }

    private fun measured(meta: YtArchiveMeta): YtArchiveMeta {
        val (text, audio, video) = store.measure(meta.videoId)
        return store.update(meta.videoId) { it.copy(textBytes = text, audioBytes = audio, videoBytes = video) } ?: meta
    }

    private fun sabr(streams: Streams) = streams.serverAbrStreamingUrl != null && streams.videoPlaybackUstreamerConfig != null

    private fun choice(stream: PipedStream) = YtArchiveRules.StreamChoice(
        url = stream.url,
        mimeType = stream.mimeType,
        codec = stream.codec,
        bitrate = stream.bitrate,
        height = stream.height,
        contentLength = stream.contentLength,
        drc = stream.isDrc == true,
        trackType = stream.audioTrackType,
    )

    /**
     * One stream into [target] with LibreTube's providers (as DownloadService does it), written
     * to a temporary file and renamed when complete, so a half file never counts.
     */
    private suspend fun downloadStream(videoId: String, streams: Streams, stream: PipedStream, type: FileType, target: File) {
        val part = File(target.parentFile, target.name + ".part")
        part.delete()
        part.createNewFile()
        val item = DownloadItem(
            type = type,
            videoId = videoId,
            fileName = part.name,
            path = part.toPath(),
            format = stream.format,
            quality = stream.quality,
            downloadSize = stream.contentLength,
        )
        val url = stream.url
        val provider: DownloadProvider = if (url?.startsWith("http") == true) {
            RawByteStreamDownloadProvider(url.toHttpUrl())
        } else {
            runCatching { SabrDownloadProvider(item, streams, stream) }.getOrElse { throw IOException("no SABR: $it") }
        }
        var tries = 0
        try {
            part.toPath().sink(StandardOpenOption.APPEND).buffer().use { sink ->
                while (true) {
                    when (val result = provider.downloadNextChunk(item, sink)) {
                        DownloadProgressResult.DownloadComplete -> break
                        DownloadProgressResult.Failed -> {
                            if (++tries > MAX_CHUNK_RETRIES) throw IOException("stream download failed")
                            delay(500L * tries)
                        }
                        is DownloadProgressResult.Progressed -> tries = 0
                    }
                    sink.flush()
                    if (part.length() > YtArchiveRules.MAX_STREAM_BYTES) throw IOException("stream too large")
                }
            }
            if (part.length() <= 0) throw IOException("empty stream")
            target.delete()
            if (!part.renameTo(target)) throw IOException("rename failed")
        } finally {
            part.delete()
        }
    }

    /** The storyboard level of [YtArchiveRules.pickBoard] as sheets 0.jpg … and index.json. */
    private suspend fun saveBoard(streams: Streams, files: YtArchiveFiles) {
        val levels = streams.previewFrames.filter { it.urls.isNotEmpty() && it.durationPerFrame > 0 }
        val pick = YtArchiveRules.pickBoard(levels.map { YtArchiveRules.Board(it.frameWidth, it.frameHeight, it.urls.size) }) ?: return
        val level = levels[pick]
        val dir = files.storyboard
        dir.deleteRecursively()
        dir.mkdirs()
        level.urls.forEachIndexed { i, url ->
            fetchFile(url, File(dir, "$i.jpg"), MAX_IMAGE_BYTES)
        }
        val index = YtArchiveBoardIndex(
            frameWidth = level.frameWidth,
            frameHeight = level.frameHeight,
            perX = level.framesPerPageX,
            perY = level.framesPerPageY,
            durationPerFrameMs = level.durationPerFrame,
            total = level.totalCount,
            sheets = level.urls.size,
        )
        File(dir, BOARD_INDEX).writeText(json.encodeToString(YtArchiveBoardIndex.serializer(), index))
    }

    /** A small file (image) via GET, at most [maxBytes]. */
    private suspend fun fetchFile(url: String, target: File, maxBytes: Long) = runInterruptible(Dispatchers.IO) {
        val request = Request.Builder().url(url).header("User-Agent", USER_AGENT).build()
        client.newCall(request).execute().use { response ->
            if (response.code == 429) throw Blocked("429 image")
            if (!response.isSuccessful) throw IOException("HTTP ${response.code}")
            val bytes = response.body.source().use { source ->
                val buffer = okio.Buffer()
                while (source.read(buffer, 8192) != -1L) {
                    if (buffer.size > maxBytes) throw IOException("image too large")
                }
                buffer.readByteArray()
            }
            val tmp = File(target.parentFile, target.name + ".tmp")
            tmp.writeBytes(bytes)
            if (!tmp.renameTo(target)) {
                target.delete()
                tmp.renameTo(target)
            }
        }
    }

    /**
     * A light "is it still there?" request: YouTube's oEmbed answer for the video (a small JSON,
     * no stream info). True: still there (200), false: not answered with 200 (private, deleted,
     * or embedding off); a block throws [Blocked], a network error the IOException.
     */
    suspend fun oEmbedOk(videoId: String): Boolean = runInterruptible(Dispatchers.IO) {
        val url = "https://www.youtube.com/oembed?format=json&url=https://www.youtube.com/watch?v=$videoId"
        val request = Request.Builder().url(url).header("User-Agent", USER_AGENT).build()
        client.newCall(request).execute().use { response ->
            if (response.code == 429) throw Blocked("429 oembed")
            response.code == 200
        }
    }

    companion object {
        private const val TAG = "YtArchiveFetcher"
        private const val MAX_CHUNK_RETRIES = 3
        private const val MAX_IMAGE_BYTES = 2L * 1024 * 1024
        private const val MAX_DESCRIPTION = 20_000
        const val BOARD_INDEX = "index.json"

        /** The same browser identity as the app's NewPipe downloader. */
        private const val USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:135.0) Gecko/20100101 Firefox/135.0"

        /** The 320×180 thumbnail (~15–25 KB) instead of the largest one of the feed. */
        fun thumbnailUrl(videoId: String) = "https://i.ytimg.com/vi/$videoId/mqdefault.jpg"
    }
}
