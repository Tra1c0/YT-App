package com.github.libretube.ui.yt.news

/*
 * YT: the transcript side of the news summaries, free of Android so it runs on the JVM. A caption
 * file (TTML, WebVTT or SRT, whatever the stream extractor hands out) becomes timed cues, the cues
 * become short passages, and the passages become one plain-text document with a "[m:ss]" stamp per
 * line. The document keeps where each line starts, so a citation's character index in the answer
 * maps back to the second the statement was said.
 */

/** One caption line: when it starts (seconds) and what is said. */
data class YtNewsCue(val startSec: Double, val text: String)

/** A caption track as the picker needs it: its language tag and whether it was made by speech recognition. */
data class YtNewsTrack(val code: String?, val autoGenerated: Boolean)

object YtNewsCaptions {
    private val TTML_P = Regex("""<p\b([^>]*)>(.*?)</p>""", setOf(RegexOption.DOT_MATCHES_ALL, RegexOption.IGNORE_CASE))
    private val BEGIN = Regex("""\bbegin\s*=\s*"([^"]+)"""")
    private val BR = Regex("""<br\s*/?>""", RegexOption.IGNORE_CASE)
    private val TAG = Regex("""<[^>]*>""")
    private val ARROW = Regex("""^\s*(\S+)\s+-->\s+(\S+)""")
    private val ENTITY = Regex("""&(#x[0-9a-fA-F]+|#\d+|amp|lt|gt|quot|apos|nbsp);""")
    private val SPACES = Regex("""\s+""")

    /** Speaker and sound marks that carry no statement: "[Musik]", "(Applaus)", "♪". */
    private val NOISE = Regex("""\[[^\]]*]|\([^)]*\)|[♪♫]""")

    /** The cues of a caption file; the format is recognised from the text itself. */
    fun parse(body: String): List<YtNewsCue> {
        val text = body.removePrefix("﻿")
        val head = text.trimStart()
        val raw = when {
            head.startsWith("WEBVTT") -> parseArrowed(text)
            head.startsWith("<") || TTML_P.containsMatchIn(text) -> parseTtml(text)
            text.contains("-->") -> parseArrowed(text)
            else -> emptyList()
        }
        return dedupe(raw)
    }

    private fun parseTtml(text: String): List<YtNewsCue> = TTML_P.findAll(text).mapNotNull { match ->
        val begin = BEGIN.find(match.groupValues[1])?.groupValues?.get(1) ?: return@mapNotNull null
        val start = time(begin) ?: return@mapNotNull null
        val words = clean(BR.replace(match.groupValues[2], " "))
        if (words.isEmpty()) null else YtNewsCue(start, words)
    }.toList()

    /** WebVTT and SRT: a "start --> end" line, then the text lines up to a blank line. */
    private fun parseArrowed(text: String): List<YtNewsCue> {
        val out = ArrayList<YtNewsCue>()
        var start: Double? = null
        val lines = ArrayList<String>()
        fun flush() {
            val at = start
            if (at != null) {
                for (line in lines) {
                    val words = clean(line)
                    if (words.isNotEmpty()) out += YtNewsCue(at, words)
                }
            }
            start = null
            lines.clear()
        }
        for (line in text.replace("\r", "").split('\n')) {
            val arrow = ARROW.find(line)
            when {
                arrow != null -> {
                    flush()
                    start = time(arrow.groupValues[1])
                }
                line.isBlank() -> flush()
                start != null -> lines += line
            }
        }
        flush()
        return out
    }

    /**
     * Speech-recognition captions roll: each cue repeats the line before and adds words. A line
     * equal to one of the last two kept lines is dropped, so every sentence is kept once.
     */
    private fun dedupe(cues: List<YtNewsCue>): List<YtNewsCue> {
        val out = ArrayList<YtNewsCue>(cues.size)
        for (cue in cues) {
            val last = out.lastOrNull()?.text
            val before = out.getOrNull(out.size - 2)?.text
            if (cue.text == last || cue.text == before) continue
            out += cue
        }
        return out.sortedBy { it.startSec }
    }

    /** One caption line without markup, entities, sound marks and extra spaces. */
    private fun clean(raw: String): String {
        var text = TAG.replace(raw, " ")
        text = ENTITY.replace(text) { entity(it.groupValues[1]) }
        text = NOISE.replace(text, " ")
        text = text.replace('>', ' ').replace(' ', ' ')
        return SPACES.replace(text, " ").trim().trimStart('-', ' ').trim()
    }

    private fun entity(name: String): String = when {
        name == "amp" -> "&"
        name == "lt" -> "<"
        name == "gt" -> ">"
        name == "quot" -> "\""
        name == "apos" -> "'"
        name == "nbsp" -> " "
        name.startsWith("#x") -> name.drop(2).toIntOrNull(16)?.let { String(Character.toChars(it)) } ?: ""
        else -> name.drop(1).toIntOrNull()?.let { String(Character.toChars(it)) } ?: ""
    }

    /**
     * A caption time in seconds: "01:02:03.456", "02:03,456" (SRT), "3.5s", "1500ms", "45000t"
     * (ticks of 10 MHz, TTML's default tick rate). Null when unreadable.
     */
    fun time(raw: String): Double? {
        val value = raw.trim()
        return when {
            value.endsWith("ms") -> value.dropLast(2).toDoubleOrNull()?.div(1000.0)
            value.endsWith("s") -> value.dropLast(1).toDoubleOrNull()
            value.endsWith("t") -> value.dropLast(1).toDoubleOrNull()?.div(10_000_000.0)
            value.contains(':') -> {
                val parts = value.replace(',', '.').split(':')
                if (parts.size !in 2..4) return null
                // hh:mm:ss:frames: the frames are dropped
                val clock = if (parts.size == 4) parts.dropLast(1) else parts
                var seconds = 0.0
                for (part in clock) seconds = seconds * 60 + (part.toDoubleOrNull() ?: return null)
                seconds
            }
            else -> value.toDoubleOrNull()
        }?.takeIf { it >= 0 }
    }

    /**
     * Which track to read, as an index into [tracks], or null when there is none. The language
     * of the speech-recognition track is the language spoken in the video; a manual track in that
     * language is best, else the recognised one. Without a recognised track the language is
     * unknown: a manual track in one of [preferred] (base codes such as "de"), else the first.
     */
    fun pick(tracks: List<YtNewsTrack>, preferred: List<String> = listOf("de", "en")): Int? {
        if (tracks.isEmpty()) return null
        val spoken = tracks.indexOfFirst { it.autoGenerated }
        if (spoken >= 0) {
            val language = base(tracks[spoken].code)
            val manual = tracks.indexOfFirst { !it.autoGenerated && language != null && base(it.code) == language }
            return if (manual >= 0) manual else spoken
        }
        for (language in preferred) {
            val manual = tracks.indexOfFirst { base(it.code) == language }
            if (manual >= 0) return manual
        }
        return 0
    }

    private fun base(code: String?): String? =
        code?.trim()?.lowercase()?.substringBefore('-')?.substringBefore('_')?.takeIf { it.isNotEmpty() }
}

/**
 * The transcript as one plain-text document: a line "[m:ss] words" per passage. [starts] holds the
 * character offset (in Unicode code points, as the API counts) where each line begins, [seconds]
 * the second the line starts at. [cut] is true when the transcript was longer than the limit.
 */
class YtNewsTranscriptDoc private constructor(
    val text: String,
    private val starts: IntArray,
    private val seconds: LongArray,
    val cut: Boolean,
) {
    val lines: Int get() = starts.size

    /** The second of the line a character (code point offset) belongs to; null for an empty document. */
    fun secondAt(codePoint: Int): Long? {
        if (starts.isEmpty()) return null
        var lo = 0
        var hi = starts.size - 1
        while (lo < hi) {
            val mid = (lo + hi + 1) ushr 1
            if (starts[mid] <= codePoint) lo = mid else hi = mid - 1
        }
        return seconds[lo]
    }

    /**
     * The second a citation points at: [startIndex] as the API reported it, checked against
     * [citedText]. When the quoted text is not found there (a different way of counting), the
     * quote itself is looked up in the document.
     */
    fun resolve(startIndex: Int, citedText: String?): Long? {
        val quote = citedText?.trim().orEmpty().take(QUOTE_CHECK)
        if (quote.isEmpty()) return secondAt(startIndex)
        val total = text.codePointCount(0, text.length)
        if (startIndex in 0 until total) {
            val at = text.offsetByCodePoints(0, startIndex)
            // the quote may begin with the spaces the index points at
            if (text.regionMatches(at, quote, 0, quote.length) ||
                text.substring(at).trimStart().startsWith(quote)
            ) {
                return secondAt(startIndex)
            }
        }
        val found = text.indexOf(quote)
        if (found >= 0) return secondAt(text.codePointCount(0, found))
        return if (startIndex in 0 until total) secondAt(startIndex) else null
    }

    companion object {
        /** About 40k tokens: a long news programme fits, a 3-hour stream does not. */
        const val MAX_CHARS = 160_000

        /** A passage closes at the end of a sentence once it has this many letters… */
        private const val MIN_PASSAGE = 80

        /** …and in any case at this many letters or seconds. */
        private const val MAX_PASSAGE = 220
        private const val MAX_SPAN_SEC = 20.0

        private const val QUOTE_CHECK = 40

        private val SENTENCE_END = Regex("""[.!?…]["»“”']?$""")

        /** The document of [cues]; at most [maxChars] characters, cut at a whole line. */
        fun build(cues: List<YtNewsCue>, maxChars: Int = MAX_CHARS): YtNewsTranscriptDoc {
            val out = StringBuilder()
            val starts = ArrayList<Int>()
            val seconds = ArrayList<Long>()
            var codePoints = 0
            var cut = false
            for ((start, words) in passages(cues)) {
                val line = "[${stamp(start)}] $words\n"
                if (out.length + line.length > maxChars) {
                    cut = true
                    break
                }
                starts += codePoints
                seconds += start
                out.append(line)
                codePoints += line.codePointCount(0, line.length)
            }
            return YtNewsTranscriptDoc(out.toString(), starts.toIntArray(), seconds.toLongArray(), cut)
        }

        /** Cues joined into passages of about a sentence: (start second, words). */
        fun passages(cues: List<YtNewsCue>): List<Pair<Long, String>> {
            val out = ArrayList<Pair<Long, String>>()
            var start = 0.0
            val words = StringBuilder()
            fun close() {
                if (words.isNotEmpty()) out += start.toLong() to words.toString()
                words.clear()
            }
            for (cue in cues) {
                if (words.isNotEmpty() && cue.startSec - start > MAX_SPAN_SEC) close()
                if (words.isEmpty()) start = cue.startSec else words.append(' ')
                words.append(cue.text)
                val long = words.length >= MAX_PASSAGE
                val ends = words.length >= MIN_PASSAGE && SENTENCE_END.containsMatchIn(words)
                if (long || ends) close()
            }
            close()
            return out
        }

        /** "m:ss", or "h:mm:ss" from an hour on. */
        fun stamp(seconds: Long): String {
            val s = seconds.coerceAtLeast(0)
            val h = s / 3600
            val m = (s % 3600) / 60
            val sec = s % 60
            return if (h > 0) "%d:%02d:%02d".format(h, m, sec) else "%d:%02d".format(m, sec)
        }
    }
}
